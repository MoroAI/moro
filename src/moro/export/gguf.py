"""
GGUF export via llama.cpp's convert_hf_to_gguf.py.

Generates a shell script and instructions since llama.cpp is not bundled.
Optionally invokes the converter if llama_cpp_python is installed.
"""

from __future__ import annotations

import re
import shlex
import subprocess
import sys
from pathlib import Path

from moro.core.errors import ExportError


def validate_conversion(quantization: str, project_name: str) -> None:
    if quantization not in {
        "f16",
        "q4_0",
        "q4_1",
        "q5_0",
        "q5_1",
        "q8_0",
        "q2_k",
        "q3_k_s",
        "q3_k_m",
        "q3_k_l",
        "q4_k_s",
        "q4_k_m",
        "q5_k_s",
        "q5_k_m",
        "q6_k",
    }:
        raise ExportError("Unsupported GGUF quantization")
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,127}", project_name):
        raise ExportError("GGUF project name must be a safe filename slug")


def write_gguf_script(
    merged_model_dir: Path,
    out_dir: Path,
    quantization: str = "q4_k_m",
    project_name: str = "model",
) -> Path:
    """
    Write a shell script that converts the merged model to GGUF using llama.cpp.

    Returns the script path.
    """
    validate_conversion(quantization, project_name)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    script_content = f"""\
#!/usr/bin/env bash
# MoroAI — GGUF conversion script for {project_name}
# Generated by `moro export --format gguf`
#
# Requirements:
#   git clone https://github.com/ggerganov/llama.cpp
#   cd llama.cpp && make -j4
#   pip install -r requirements/requirements-convert_hf_to_gguf.txt
#
# Usage:
#   chmod +x convert_to_gguf.sh && ./convert_to_gguf.sh

set -euo pipefail

LLAMA_CPP="${{LLAMA_CPP_PATH:-./llama.cpp}}"
MERGED_MODEL={shlex.quote(str(merged_model_dir.resolve()))}
OUTPUT_DIR={shlex.quote(str(out_dir.resolve()))}
QUANTIZATION={shlex.quote(quantization)}
MODEL_NAME={shlex.quote(project_name)}

if [ ! -f "$LLAMA_CPP/convert_hf_to_gguf.py" ]; then
  echo "ERROR: llama.cpp not found at $LLAMA_CPP"
  echo "Clone llama.cpp and set LLAMA_CPP_PATH to its location."
  exit 1
fi

echo "→ Converting to F16 GGUF..."
python "$LLAMA_CPP/convert_hf_to_gguf.py" \\
  --outtype f16 \\
  --outfile "$OUTPUT_DIR/${{MODEL_NAME}}-f16.gguf" \\
  "$MERGED_MODEL"

if [ "$QUANTIZATION" = f16 ]; then
  echo "F16 output is ready."
  exit 0
fi

echo "→ Quantizing to $QUANTIZATION..."
"$LLAMA_CPP/llama-quantize" \\
  "$OUTPUT_DIR/${{MODEL_NAME}}-f16.gguf" \\
  "$OUTPUT_DIR/${{MODEL_NAME}}-${{QUANTIZATION}}.gguf" \\
  "$QUANTIZATION"

echo "✓ Done: $OUTPUT_DIR/${{MODEL_NAME}}-${{QUANTIZATION}}.gguf"
echo ""
echo "To run with llama.cpp:"
echo "  $LLAMA_CPP/llama-cli -m $OUTPUT_DIR/${{MODEL_NAME}}-${{QUANTIZATION}}.gguf -i"
echo ""
echo "To run with Ollama:"
echo "  MODEL_FILE: FROM $OUTPUT_DIR/${{MODEL_NAME}}-${{QUANTIZATION}}.gguf"
"""

    script_path = out_dir / "convert_to_gguf.sh"
    script_path.write_text(script_content, encoding="utf-8")
    script_path.chmod(0o755)
    return script_path


def convert_to_gguf_direct(
    merged_model_dir: Path,
    out_dir: Path,
    llama_cpp_path: Path,
    quantization: str = "q4_k_m",
    project_name: str = "model",
) -> Path:
    """
    Directly invoke llama.cpp conversion if llama.cpp is available locally.

    Returns the path to the quantized GGUF file.
    """
    merged_model_dir = Path(merged_model_dir).resolve()
    validate_conversion(quantization, project_name)
    out_dir = Path(out_dir)
    llama_cpp_path = Path(llama_cpp_path)
    out_dir.mkdir(parents=True, exist_ok=True)

    converter = llama_cpp_path / "convert_hf_to_gguf.py"
    quantizer = llama_cpp_path / "llama-quantize"

    if not converter.exists():
        raise ExportError(f"convert_hf_to_gguf.py not found in: {llama_cpp_path}")
    if quantization != "f16" and not quantizer.exists():
        raise ExportError(f"llama-quantize not found in: {llama_cpp_path}")

    python = sys.executable

    f16_path = out_dir / f"{project_name}-f16.gguf"

    # Step 1: Convert to F16
    subprocess.run(
        [
            python,
            str(converter),
            "--outtype",
            "f16",
            "--outfile",
            str(f16_path),
            str(merged_model_dir),
        ],
        check=True,
        timeout=3600,
    )

    if quantization == "f16":
        if not f16_path.is_file() or not f16_path.stat().st_size:
            raise ExportError("Converter produced no F16 output")
        return f16_path

    # Step 2: Quantize
    quant_path = out_dir / f"{project_name}-{quantization}.gguf"
    subprocess.run(
        [str(quantizer), str(f16_path), str(quant_path), quantization],
        check=True,
        timeout=3600,
    )

    if not quant_path.is_file() or not quant_path.stat().st_size:
        raise ExportError("Quantizer produced no output")

    # Remove intermediate F16 to save disk
    if f16_path.exists() and quant_path.exists():
        f16_path.unlink()

    return quant_path
